@Injectable({ providedIn: 'root' })
export class TranslationService {
  readonly language = signal<Language>(this.initialLanguage());
  text(key: TranslationKey | string): string {
    const dictionary: Readonly<Record<string, string>> = this.language() === 'pt-BR' ? PT : EN;
    return dictionary[key] ?? key;
  }
  setLanguage(language: Language): void {
    this.language.set(language);
    localStorage.setItem('dsd-language', language);
  }
  private initialLanguage(): Language {
    const saved = localStorage.getItem('dsd-language');
    if (saved === 'en' || saved === 'pt-BR') return saved;
    return navigator.language.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
  }
}
